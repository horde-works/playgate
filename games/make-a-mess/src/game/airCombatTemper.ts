/**
 * НРАВ ОХОТНИКА: состояние, которое НЕ является положением.
 *
 * Автомат боя до сих пор каждый кадр заново спрашивал «что сейчас лучше». Это
 * и есть то, что делает его скучным: у него нет ничего, что тянулось бы во
 * времени, кроме ярлыка на геометрии. Зверь так не устроен — он спрашивает «что
 * я сейчас делаю», и ответ зависит от того, что с ним уже случилось.
 *
 * Здесь живёт ровно то, чего нельзя вывести из нынешнего кадра. Это важная
 * граница, и она проведена сознательно:
 *
 *   - СКУПОСТЬ выводится из остатка в поду. Памяти не нужно;
 *   - ТЯГА ДОМОЙ выводится из выноса от поста. Памяти не нужно;
 *   - СТРАХ ЗЕМЛИ выводится из высоты. Памяти не нужно.
 *
 * А вот АЗАРТ и ДОСАДА не выводятся ниоткуда: они и есть история. Кровь меняет
 * ставки; три пустых захода подряд рождают отвращение к повторению. Поэтому
 * состояния здесь два, и памяти при них — одна: чем заходили в последний раз.
 *
 * И одна вещь, которую этот модуль НЕ отменяет. Зверь не передумывает посреди
 * прыжка — закон «заход есть обязательство» остаётся. Нрав задаёт, КАКОЙ будет
 * бросок и когда он начнётся; внутри броска он молчит.
 */

export interface CombatTemper {
  /**
   * АЗАРТ, 0..1. Растёт от попаданий, тает со временем.
   *
   * Не «уверенность» и не «мораль». Это готовность рисковать: подойти ближе,
   * опуститься ниже, задержаться на заходе дольше разумного. Раненый стоит
   * риска — это правило старше любой авиации.
   */
  readonly appetite: number;
  /**
   * ДОСАДА, 0..1. Растёт от пустых заходов, обнуляется попаданием.
   *
   * Единственный источник разнообразия, который не требует перебора. Не «выбери
   * лучшее из восьми», а «то же самое больше не буду» — и повадка сама
   * перестаёт быть однообразной.
   */
  readonly frustration: number;
  /** Чем заходили в последние разы. Нужна только досаде — чтобы не повторять. */
  readonly recentApproaches: readonly number[];
}

/** Что случилось за кадр. Ничего про геометрию: только события. */
export interface CombatTemperEvents {
  readonly seconds: number;
  /** Попаданий за этот кадр — любым стволом. */
  readonly hits: number;
  /** Заход кончился именно сейчас. */
  readonly passEnded: boolean;
  /** И был ли он результативным. */
  readonly passScored: boolean;
  /** Чем заходили: код подхода, см. `approachCode`. */
  readonly approach: number;
}

export const IDLE_COMBAT_TEMPER: CombatTemper = {
  appetite: 0,
  frustration: 0,
  recentApproaches: [],
};

/**
 * ПОЛУРАСПАД АЗАРТА, с. Взят равным ЦИКЛУ ЗАХОДА, а не назначен: атака до 6 с,
 * срыв до 2.2, отставание до 3 — около одиннадцати секунд на круг. Восемь
 * означает «одно попадание доносит смелость до следующего захода, но не до
 * третьего». Дольше — и машина храбрится, ничего давно не добившись.
 */
const APPETITE_HALF_LIFE = 8;
/**
 * Сколько азарта даёт одно попадание. Треть: одно попадание заметно, три
 * подряд — предел. Одиночная случайная удача не должна превращать сторожа в
 * камикадзе.
 */
const APPETITE_PER_HIT = 0.34;
/**
 * Сколько досады даёт пустой заход. Треть по той же причине, по которой в прозе
 * стояло «три раза подряд одинаково — противно повторять».
 */
const FRUSTRATION_PER_EMPTY_PASS = 0.34;
/** Сколько подходов помнить. Двух хватает, чтобы перебирать, а не метаться. */
const APPROACH_MEMORY = 2;

/** Подход — это сторона и ярус. Четыре штуки, и кодируются одним числом. */
export function approachCode(side: number, vertical: number): number {
  return (side >= 0 ? 1 : 0) * 2 + (vertical >= 0 ? 1 : 0);
}

export function approachSide(code: number): number {
  return code >= 2 ? 1 : -1;
}

export function approachVertical(code: number): number {
  return code % 2 === 1 ? 1 : -1;
}

export const APPROACHES: readonly number[] = [0, 1, 2, 3];

export function advanceCombatTemper(
  temper: CombatTemper,
  events: CombatTemperEvents,
): CombatTemper {
  // Азарт тает непрерывно и прибавляется событиями. Экспонента, а не линейка:
  // затухание должно быть быстрым сразу после и медленным потом, иначе смелость
  // обрывается на ровном месте.
  const decay = Math.pow(0.5, events.seconds / APPETITE_HALF_LIFE);
  let appetite = temper.appetite * decay + events.hits * APPETITE_PER_HIT;
  appetite = Math.max(0, Math.min(1, appetite));

  let frustration = temper.frustration;
  let recentApproaches = temper.recentApproaches;
  if (events.passEnded) {
    if (events.passScored) {
      // Получилось — досады нет, и память чистится: работающий подход
      // повторять МОЖНО и НУЖНО. «Не то же самое» относится к неудаче, а не к
      // разнообразию ради разнообразия.
      frustration = 0;
      recentApproaches = [];
    } else {
      frustration = Math.min(1, frustration + FRUSTRATION_PER_EMPTY_PASS);
      recentApproaches = [events.approach, ...recentApproaches].slice(
        0,
        APPROACH_MEMORY,
      );
    }
  }
  return { appetite, frustration, recentApproaches };
}

/**
 * ЧЕМ ЗАХОДИТЬ В СЛЕДУЮЩИЙ РАЗ.
 *
 * Пока получается — тем же. Как только перестало — чем угодно, кроме того, что
 * уже не сработало. Ни перебора, ни оценки: отвращение к повторению и есть весь
 * механизм.
 *
 * Выбор среди неопробованных — детерминированный, по кругу от нынешнего.
 * Случайности здесь не место: бой обязан воспроизводиться на стенде.
 */
export function chooseApproach(
  temper: CombatTemper,
  current: number,
): number {
  if (temper.recentApproaches.length === 0) return current;
  for (let step = 1; step <= APPROACHES.length; step += 1) {
    const candidate = (current + step) % APPROACHES.length;
    if (!temper.recentApproaches.includes(candidate)) return candidate;
  }
  // Всё перепробовано и всё пусто — возвращаемся к началу круга. Это не сдача:
  // за время перебора обстановка изменилась, и первый подход уже другой.
  return (current + 1) % APPROACHES.length;
}

/**
 * НАСКОЛЬКО БЛИЗКО ПОДПУСКАТЬ СЕБЯ К ЦЕЛИ.
 *
 * Срыв захода назначен паспортом как безопасная дистанция. Азарт её ужимает:
 * зверь, попробовавший крови, подходит ближе, чем стоило бы.
 *
 * ПЯТНАДЦАТЬ ПРОЦЕНТОВ, А НЕ ТРЕТЬ, И ЭТО ЗАМЕР, А НЕ ОСТОРОЖНОСТЬ. Треть
 * оказалась не «характером», а прямым усилением: ближе — значит убойнее, и
 * охотник начал валить гостя города за двадцать две секунды в два захода.
 * Разом сломались две вещи, обе записанные раньше и обе не про баланс:
 *
 *   - вердикт Igor «желательно, чтобы атакующий не сбивал цель с первого раза»
 *     повис на волоске — заходов осталось ровно два;
 *   - злой маршрут перестал отличаться от ровного круга (22.0 против 23.7 с),
 *     то есть уклонение обесценилось. Цель, которой незачем уклоняться, — это
 *     мишень, а не противник.
 *
 * Азарт обязан менять ПОВАДКУ, а не таблицу урона. Поэтому подпуск оставлен
 * заметным, но небольшим, а настоящая смелость выражена там, где она ничего не
 * умножает: ниже к земле и дольше на заходе.
 */
export function pressedBreakRange(temper: CombatTemper, base: number): number {
  return base * (1 - 0.15 * temper.appetite);
}

/**
 * НАСКОЛЬКО РАНО ОТВОРАЧИВАТЬ ОТ ЗЕМЛИ.
 *
 * Страх земли выводится из высоты и памяти не требует — но азарт его приглушает.
 * Это и есть «риск землёй ради раненого», и это единственное место, где нрав
 * трогает безопасность. Ниже сорока процентов запаса не опускается никогда:
 * смелость смелостью, а земля не договаривается.
 */
export function daredFloor(temper: CombatTemper, base: number): number {
  // ЧЕТВЕРТЬ, А НЕ ТРИ ПЯТЫХ. Шестьдесят процентов запаса — это не смелость, а
  // безрассудство, которое окупается только потому, что стенд не бьёт охотника
  // о землю. В прозе зверь землю БОИТСЯ и вниз за добычей идёт неохотно; азарт
  // этот страх приглушает, а не отменяет.
  return base * (1 - 0.25 * temper.appetite);
}

/**
 * СКУПОСТЬ: насколько строже проверять выстрел, когда в поду мало.
 *
 * Выводится из остатка, памяти не требует. Полный под — щедрость: ракета
 * дешева, окно дорого. Последняя ракета — выбирать: она стоит того, чтобы
 * подождать хорошего момента, потому что следующая будет через полминуты.
 *
 * Возвращается МНОЖИТЕЛЬ к допустимому уходу цели: единица — как есть, меньше —
 * требовать более верного выстрела.
 */
export function thrift(rocketsLeft: number, podSize: number): number {
  if (podSize <= 0) return 1;
  const share = Math.max(0, Math.min(1, rocketsLeft / podSize));
  // Треть пода и меньше — начинаем считать. Выше — не жадничаем вовсе.
  return share >= 0.34 ? 1 : 0.5 + 1.5 * share;
}

/**
 * ПУСТОЙ ПОД — ЭТО ПОВЕДЕНИЕ, А НЕ СЧЁТЧИК.
 *
 * Зверь без яда не улетает. Он висит рядом, держит давление и ждёт, пока
 * снарядится: преследователь, который не отстаёт, страшнее вооружённого,
 * который ушёл. Практически это означает КОРОТКИЙ ПОВОДОК на отставании —
 * дальше отходить незачем, всё равно нечем бить.
 */
export function shadowing(rocketsLeft: number, reloading: boolean): boolean {
  return reloading || rocketsLeft <= 0;
}

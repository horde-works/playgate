/** Скорость отброса на этом расстоянии. Спад — тот же, что у тел. */
export function waveSpeed(wave: BlastWave, distance: number): {
  horizontal: number;
  vertical: number;
} {
  const falloff = Math.max(0, 1 - distance / wave.pushRadius);
  return {
    horizontal: wave.horizontal * falloff,
    vertical: wave.vertical * falloff,
  };
}

/** Куда и как долго летит тело. Баллистика, а не выдуманная дуга. */
export function flightOf(horizontal: number, vertical: number): {
  seconds: number;
  reach: number;
  peak: number;
} {
  const seconds = Math.max(0.18, (2 * vertical) / GRAVITY);
  return {
    seconds,
    reach: horizontal * seconds,
    peak: (vertical * vertical) / (2 * GRAVITY),
  };
}

/** Событие шума. Кто шумел — не важно; важны место, уровень и фронт. */
export interface NoiseEvent {
  readonly x: number;
  readonly y: number;
  readonly z: number;
  /** Уровень на расстоянии 1 м, дБ. */
  readonly level: number;
  /**
   * Крутизна фронта, 0..1. Рефлекс вызывает РЕЗКИЙ звук: у выстрела фронт
   * почти единица, у оседающего сруба — треть.
   */
  readonly rise: number;
  /** Волна, если она есть. У выстрела её нет, у взрыва есть. */
  readonly wave?: BlastWave;
  /**
   * Это ЗНАК, а не хлопок: рог, било, крик. Не пугает и не заставляет искать
   * источник, но понятен сразу и всем, кто его слышит.
   */
  readonly signal?: boolean;
}

/** Событие в пути: звук идёт 343 м/с и до дальнего края доходит позже. */
export interface PendingNoise extends NoiseEvent {
  /** Секунд с момента события. */
  age: number;
  /** Кому уже дошло: индекс жителя → 0/1. */
  readonly delivered: Uint8Array;
  /** Скольким ещё не дошло — чтобы выбрасывать доставленное целиком. */
  left: number;
}

function clamp01(value: number): number {
  return value < 0 ? 0 : value > 1 ? 1 : value;
}

/**
 * Уровень на расстоянии: −6 дБ на удвоение (закон обратных квадратов).
 * Ближе метра не считаем: там формула уходит в бесконечность, а человек всё
 * равно уже получил максимум.
 */
export function levelAtDistance(level: number, distance: number): number {
  return level - 20 * Math.log10(Math.max(1, distance));
}

/** Сколько секунд звук идёт до слушателя. */
export function travelTime(distance: number): number {
  return distance / SPEED_OF_SOUND;
}

/**
 * Амплитуда вздрога: ноль на пороге рефлекса, единица на полном уровне,
 * с поправкой на крутизну фронта и на привычку.
 */
export function startleAmplitude(
  level: number,
  rise: number,
  habituation: number,
): number {
  const above = (level - STARTLE_FLOOR_DB) / (STARTLE_FULL_DB - STARTLE_FLOOR_DB);
  return (
    clamp01(above) * clamp01(rise) * (1 - HABITUATION_DEPTH * clamp01(habituation))
  );
}

/**
 * Привычка, С КОТОРОЙ ВСТРЕЧАЮТ ЭТО СОБЫТИЕ. Сенситизация действует на само
 * событие, а не на следующее: человек, привыкший к пальбе, от взрыва в трёх
 * метрах не вздрагивает вполсилы — его сбрасывает в ноль этим самым взрывом.
 *
 * Детектор поймал ровно это: привыкшему давали 0.27 вместо полной амплитуды,
 * потому что привычка обнулялась ПОСЛЕ того, как по ней уже посчитали вздрог.
 */
export function habituationFor(habituation: number, level: number): number {
  return level >= SENSITIZE_DB ? 0 : habituation;
}

/**
 * Привычка после события. Копится долями оставшегося запаса, поэтому первые
 * повторы гасят сильно, а десятый уже почти ничего не меняет — так и устроено
 * привыкание.
 */
export function habituationAfter(
  habituation: number,
  level: number,
  gain: number = HABITUATION_GAIN,
): number {
  if (level >= SENSITIZE_DB) {
    return 0;
  }
  return habituation + (1 - habituation) * gain;
}

/** Угасание привычки в тишине. */
export function habituationDecay(habituation: number, step: number): number {
  return habituation * Math.exp(-step / HABITUATION_TAU);
}

/**
 * Форма вздрога во времени, 0..1. Быстрый подъём и более долгий спад: пик
 * приходится примерно на пятую часть длительности, то есть на ~85 мс после
 * начала движения. Ровный колокол здесь читается как приседание, а не как
 * непроизвольный рефлекс.
 */
export function startleEnvelope(progress: number): number {
  if (progress <= 0 || progress >= 1) {
    return 0;
  }
  return Math.sin(Math.PI * Math.pow(progress, 0.42));
}

/**
 * ВО СКОЛЬКО РАЗ РЕФЛЕКС ГЛУШИТ ХОД.
 *
 * Самое заметное в испуге — вовсе не поза. Человек ОСЕКАЕТСЯ НА ШАГЕ: рефлекс
 * обрывает то движение, которым он был занят. Первая версия двигала только
 * голову и плечи на честные пять сантиметров — анатомически верно и на экране
 * невидимо (тот же урок, что с размером головы: точная пропорция читается
 * хуже стилизации). Остановка же читается с любого расстояния и при любом
 * ракурсе, а фаза шага у жителя растёт от ПРОЙДЕННОГО ПУТИ, поэтому
 * замедление само притормаживает ноги и стопа не скользит.
 *
 * Форма своя, не общая с позой: осечка держится почти всю длительность и
 * отпускает к концу, тогда как поза успевает подняться и опасть.
 */
export function startleBrake(progress: number, amplitude: number): number {
  if (progress <= 0 || progress >= 1) {
    return 1;
  }
  const hold =
    progress < 0.12
      ? progress / 0.12
      : progress > 0.55
        ? Math.max(0, 1 - (progress - 0.55) / 0.45)
        : 1;
  return 1 - 0.92 * clamp01(amplitude) * hold;
}

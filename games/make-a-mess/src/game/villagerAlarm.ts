export const FAMILIAR_ALERT_SCALE = 0.22;

function spread(random: () => number, range: readonly [number, number]): number {
  return range[0] + random() * (range[1] - range[0]);
}

/**
 * Ошибка направления на источник, радианы со знаком. Мелкая — почти всегда,
 * грубая — изредка.
 */
export function localisationError(random: () => number): number {
  const side = random() < 0.5 ? -1 : 1;
  if (random() < GROSS_MISS_CHANCE) {
    return side * spread(random, GROSS_MISS_SPREAD);
  }
  // Сумма трёх равномерных даёт колокол без обращения к нормальному закону.
  // У неё разброс 1/√12·√3 = 0.5, поэтому приводим к единичному и умножаем
  // на нужный: иначе промах выходит втрое мельче заявленного.
  const bell = (random() + random() + random() - 1.5) / 0.5;
  return bell * LOCALISATION_SIGMA;
}

/** Сколько длится замирание: свой запас, растянутый силой испуга. */
export function alertSeconds(span: number, amplitude: number): number {
  return span * (0.5 + 0.5 * clamp01(amplitude));
}

/**
 * Уронит ли ношу. Слабый вздрог руки не разжимает; сильный — разжимает
 * примерно в половине случаев. Выронённая единица уже списана со склада и до
 * приёмника не доедет — вот и вся цена шума, без единого трупа.
 */
export function dropsLoad(amplitude: number, random: () => number): boolean {
  return random() < clamp01(amplitude - 0.5);
}

/**
 * Насколько сильно видна настороженность: полсекунды на вход, полсекунды на
 * выход. Резкий переход читается щелчком, а не человеком.
 */
export function alertPose(age: number, left: number, peak: number): number {
  return (
    clamp01(peak) * Math.min(1, Math.max(0, age) / 0.3, Math.max(0, left) / 0.45)
  );
}


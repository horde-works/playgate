/**
 * ГЕКСАКОПТЕР «HX-6» НА ПЛОЩАДКЕ В ЧАСТНОМ ДВОРЕ
 * ==================================================
 *
 * Паспорт образа
 * --------------
 * Роль: одноместный городской аппарат вертикального взлёта, оставленный на
 * размеченном пятне посреди двора. Эмоция — дорогая, чистая, чужая вещь среди
 * панельных домов: контраст и есть смысл размещения.
 *
 * Фраза силуэта: **шестилучевая звезда из колец, над которой на короткой шее
 * стоит гранёный стеклянный фонарь.**
 *
 * Шесть фирменных черт (без них не читается):
 *  1. шесть КОЛЬЦЕВЫХ КОЖУХОВ по вершинам правильного шестиугольника, каждый —
 *     самостоятельный движитель с толстой каплевидной губой на входе;
 *  2. ГРАНЁНЫЙ ФОНАРЬ: тёмное стекло, разрезанное полированными
 *     меридиональными рёбрами на шесть секторов (референс — модель Hiller
 *     ducted-fan и фонарь EHang 216);
 *  3. КАБИНА ВЫШЕ ПЛОСКОСТИ ВИНТОВ на короткой шее: из кресла винты видно
 *     вниз-наружу под 35°, а две вставки в полу — стеклянные;
 *  4. ЖЁСТКАЯ ЛИНИЯ ПЛЕЧА: полированный алюминий сверху, графит снизу, между
 *     ними настоящий поясной шов, а не смена цвета;
 *  5. ПОВОРОТНЫЕ КОЛЬЦА в вилках-карданах: видимая ось, щёки и привод —
 *     аппарат летит, наклоняя кольца, а не корпус, и ими же рыскает: ни киля,
 *     ни руля у него нет и быть не должно;
 *  6. ТОНКИЕ ГНУТЫЕ СТОЙКИ шасси с плоскими пятками, без лестниц и подножек:
 *     порог кабины на высоте шага, и лезть по трапу некуда.
 *
 * Пропорции (замерены по референсам, EHang 216 — 5.61 м размаха):
 *   размах по внешним губам колец  6.20 м
 *   длина                          5.62 м
 *   высота                         2.70 м   (размах/высота = 2.30)
 *   диск винта                     1.36 м,  нагрузка на диск 795 Н/м²
 *
 * Паспорт физики
 * --------------
 * Это НЕ плавучая машина: подъём даёт не оболочка, а винты. В общем контракте
 * это выражается ровно: `envelopeMatch` указывает на лопасти, поэтому
 * `liveEnvelope / intactEnvelope` — доля уцелевших лопастей, а `liftReserve`
 * становится честной тяговооружённостью. Отсюда сама собой берётся история
 * гексакоптера: одно кольцо долой — машина ещё летит, два — уже снижается.
 *
 * Продольная тяга приходит от НАКЛОНА колец: горизонтальная составляющая
 * приложена в шести точках, разнос по борту даёт рыскание. Поэтому шесть
 * каналов `throttle:0..5`, а не два.
 *
 * Момент по крену и тангажу, как и у остальных машин проекта, рождается
 * расстоянием между живым центром масс и замороженным подъёмным центром
 * (губы колец). Единственный орган управления им — настоящий груз на рельсе:
 * здесь это батарейный поддон под стеклянным полом, его видно.
 *
 * Смерть: разбить силовой шпангоут в гондоле — падает вся машина. Площадка
 * остаётся: она не несёт и не держит навесок (см. vehicle-authoring
 * references/assembly.md, пп. 10, 22).
 */

export const TOWN_HEXACOPTER_SCENE_ID = "town-vertipad";
export const TOWN_HEXACOPTER_CLUSTER_ID = "town-vertipad:hexacopter";
export const TOWN_VERTIPAD_CLUSTER_ID = "town-vertipad:pad";

/**
 * Центр размеченного пятна: точно на поперечной оси второго старого дома
 * (`h2`, центр z = -3), справа от него. По x площадка стоит в середине
 * свободного промежутка между восточной стеной дома и гаражным рядом на
 * кромке мира. Это именно двор владельца дома, а не диагональная точка у
 * угла гаражей.
 */
export const HEXACOPTER_PAD_X = 69;
export const HEXACOPTER_PAD_Z = -3;
/** Верх газона `yard:ground`; сама железобетонная плита остаётся приподнятой. */
export const HEXACOPTER_GROUND_Y = -0.02;
export const HEXACOPTER_PAD_TOP_Y = 0.14;

/**
 * Нос смотрит на запад, к дому владельца. Маршрут набирает безопасную высоту
 * до пересечения плоскости крыши, поэтому исходная ориентация машины и всей
 * её разметки после переноса сохраняется.
 */
export const HEXACOPTER_NOSE: SceneVector3 = [-1, 0, 0];
/** Правый борт машины: если смотреть по носу на запад, справа север… нет — юг. */
export const HEXACOPTER_STARBOARD: SceneVector3 = [0, 0, -1];

/**
 * Точка в системе аппарата: `a` — вперёд к носу, `b` — на правый борт,
 * `y` — мировая высота. Мир: x на восток, z на север.
 */
export function hexacopterPoint(
  a: number,
  b: number,
  y: number,
): SceneVector3 {
  return [HEXACOPTER_PAD_X - a, y, HEXACOPTER_PAD_Z - b];
}


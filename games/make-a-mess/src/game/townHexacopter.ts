/**
 * Вынос кольца от оси. Число выбрано не по красоте, а по КОМПОЗИЦИИ: при
 * 2.42 м шесть колец занимали 6.5 м и глаз читал их как сам объект, а кабину —
 * как деталь наверху; машина выглядела аттракционом. При 2.15 м размах 5.76 м,
 * кабина занимает 40% ширины и становится главной массой. Одновременно
 * уменьшены и сами кольца: диск 1.16 м даёт 1050 Н/м² нагрузки — много для
 * открытого винта и совершенно обычно для кольцевого, который на то и нужен.
 */
export const HEX_ARM_RADIUS = 2.15;
/** Радиус диска винта. */
export const HEX_FAN_RADIUS = 0.58;
export const HEX_SHROUD_INNER_RADIUS = 0.61;
export const HEX_SHROUD_OUTER_RADIUS = 0.68;
/** Внешний радиус губы — он и задаёт габарит. */
export const HEX_LIP_OUTER_RADIUS = 0.73;

/**
 * Кабина В ПЛАНЕ — ЭЛЛИПС, а не круг: тело вращения читается корпусом дрона,
 * и никакая детализация этого не чинит. Полуоси взяты от человека внутри
 * (капсула 0.72 м) плюс кресло, приборная стойка спереди и переборка сзади.
 */
export const HEX_CABIN_HALF_LENGTH = 1.15;
export const HEX_CABIN_HALF_WIDTH = 0.76;
/** Насколько пояс шире пола, и во сколько раз макушка уже пояса. */
export const HEX_CABIN_WAIST_SCALE = 1;
export const HEX_CABIN_TOP_SCALE = 0.46;
/** Верх фонаря завален назад: нос получает наклонное лобовое стекло. */
export const HEX_CABIN_TOP_RAKE = 0.14;

/** Радиус кабины в плане на угле `psi` от носа. */
export function hexacopterCabinRadius(psi: number): number {
  return (
    1 /
    Math.hypot(
      Math.cos(psi) / HEX_CABIN_HALF_LENGTH,
      Math.sin(psi) / HEX_CABIN_HALF_WIDTH,
    )
  );
}

export const HEXACOPTER_SPAN = 2 * (HEX_ARM_RADIUS + HEX_LIP_OUTER_RADIUS);
export const HEXACOPTER_LENGTH =
  2 * (HEX_ARM_RADIUS * Math.cos(Math.PI / 6) + HEX_LIP_OUTER_RADIUS);

export interface HexacopterDuctStation {
  /** Индекс канала `throttle:<index>` и номер в идентификаторах кусков. */
  readonly index: number;
  /** Угол оси кольца от носа, по часовой стрелке сверху. */
  readonly angle: number;
  readonly a: number;
  readonly b: number;
  /** −1 левый борт, +1 правый. */
  readonly side: -1 | 1;
}

/**
 * Шестиугольник ставится гранью вперёд: на носу два кольца, на траверзе два
 * самых разнесённых, на корме два. Ни одно не стоит на оси, поэтому все шесть
 * дают плечо рыскания, а не только четыре.
 */
export const HEXACOPTER_DUCTS: readonly HexacopterDuctStation[] = [
  30, 90, 150, 210, 270, 330,
].map((degrees, index) => {
  const angle = (degrees * Math.PI) / 180;
  return {
    index,
    angle,
    a: HEX_ARM_RADIUS * Math.cos(angle),
    b: HEX_ARM_RADIUS * Math.sin(angle),
    side: (Math.sin(angle) >= 0 ? 1 : -1) as -1 | 1,
  };
});

/**
 * Ноги стоят в ПРОСВЕТАХ между кольцами, а не под ними: на осях лучей места
 * для стойки нет. Просвет 300° приходится ровно под дверь левого борта.
 */
export const HEXACOPTER_GEAR_RADIUS = 1.75;
export const HEXACOPTER_GEAR_STATIONS = [60, 120, 240, 300].map((degrees) => {
  const angle = (degrees * Math.PI) / 180;
  return {
    a: HEXACOPTER_GEAR_RADIUS * Math.cos(angle),
    b: HEXACOPTER_GEAR_RADIUS * Math.sin(angle),
  };
});

/**
 * Паспорт требует точку приложения рулевой силы, но У ЭТОЙ МАШИНЫ РУЛЯ НЕТ.
 * Гексакоптер рыскает разнотягом колец — это и есть его руль, и он уже описан
 * шестью точками тяги с настоящими плечами. Сила пера поэтому нулевая, а
 * точка оставлена в корме только чтобы контракт был заполнен честным нулём,
 * а не выдуманным оперением.
 */
export const HEXACOPTER_RUDDER_POINT: SceneVector3 = hexacopterPoint(
  -HEX_ARM_RADIUS,
  0,
  HEX_DISC_Y,
);

/** Мировая точка оси кольца в плоскости диска. */
export function hexacopterDuctPoint(
  station: HexacopterDuctStation,
  y: number = HEX_DISC_Y,
): SceneVector3 {
  return hexacopterPoint(station.a, station.b, y);
}

/** Рёбра фонаря стоят на носу и через 60°, стёкла — ровно над кольцами. */
export const HEXACOPTER_CANOPY_RIBS = [0, 60, 120, 180, 240, 300];

/**
 * Рабочий объём кабины в авторской позе покоя. Действие «лететь» живёт только
 * здесь: снаружи к центру машины не подойти, кольца не пускают.
 */
export function isInsideHexacopter(point: SceneVector3): boolean {
  const a = HEXACOPTER_PAD_X - point[0];
  const b = HEXACOPTER_PAD_Z - point[2];
  return (
    (a / HEX_CABIN_HALF_LENGTH) ** 2 + (b / HEX_CABIN_HALF_WIDTH) ** 2 <= 1 &&
    point[1] >= HEX_FLOOR_Y &&
    point[1] <= HEX_CANOPY_TOP_Y
  );
}


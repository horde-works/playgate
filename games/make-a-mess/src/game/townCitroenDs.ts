/**
 * ГОРОДСКОЙ СЕДАН «DS» — ПАСПОРТ
 *
 * Первая колёсная машина проекта. Всё, что ниже, — измеримые инварианты; куски
 * собираются из них в `content/scenes/townBoulevardDocument.ts`, а силы считает
 * общий `carDynamics.ts`, который об этой машине не знает ничего.
 *
 * ── ПАСПОРТ ОБРАЗА ────────────────────────────────────────────────────────
 *
 * Одна фраза силуэта: КАПЛЯ, ЕДУЩАЯ НОСОМ ВНИЗ. Машина низкая спереди и
 * высокая сзади, широкая в плечах и сходящаяся к корме, и стоит она на земле
 * не как коробка на четырёх углах, а как существо, присевшее на передние лапы.
 *
 * Признаки эпохи и технологии, которые обязаны читаться без подписи:
 *
 *   1. ПЕРЕДНЯЯ КОЛЕЯ ШИРЕ ЗАДНЕЙ на двести миллиметров. Это не стилизация:
 *      машина переднеприводная, вся тяга и вся масса у неё спереди, а корма
 *      сужена ради обтекаемости. В плане это даёт настоящую каплю, и любая
 *      попытка поставить колёса «как обычно» убивает образ первым же кадром;
 *   2. ЗАДНИЕ КОЛЁСА ЗАКРЫТЫ ЩИТКАМИ. Их не видно вовсе — видно только вырез
 *      в юбке. Отсюда и ощущение, что корма не едет, а плывёт;
 *   3. НЕТ РЕШЁТКИ РАДИАТОРА. Воздух машина берёт низкой щелью под бампером,
 *      и оттого лоб у неё гладкий и заострённый — этого нет ни у одной другой
 *      машины тех лет;
 *   4. КРЫША СВЕТЛАЯ И ТОНКАЯ. Она не стальная: пластик поверх лёгкого
 *      каркаса. Отсюда и материал куска, и то, что при ударе она ведёт себя
 *      иначе, чем борта;
 *   5. ЧЕТЫРЕ ФАРЫ ПОД ОБЩИМ СТЕКЛОМ, и внутренняя пара ПОВОРАЧИВАЕТСЯ ВМЕСТЕ
 *      С РУЛЁМ. Это главный механизм машины и её визитная карточка: в темноте
 *      свет уходит в поворот раньше, чем туда поедет корпус;
 *   6. МАШИНА МЕНЯЕТ ПОСАДКУ. Гидропневматика самовыравнивается: гружёная
 *      корма не проседает, а на стоянке машина оседает на упоры.
 *
 * Главная масса — передняя треть с агрегатами; вторичная — длинная корма;
 * вертикальный акцент — гребень крыши над задним рядом, самая высокая точка
 * машины, и он лежит ПОЗАДИ середины.
 *
 * ── ПАСПОРТ ФИЗИКИ ────────────────────────────────────────────────────────
 *
 * Несущий корень — платформа пола: на ней стоит всё, и она же единственное,
 * что связывает переднюю подрамную группу с задней. Отделяемые группы: четыре
 * колеса, оба бампера, четыре двери, капот, крышка багажника, щитки задних
 * колёс, блок фар. Точки приложения сил — только пятна контакта колёс; больше
 * машина ни на что не опирается и ничем не толкается.
 *
 * Развесовка 65/35 на переднюю ось — свойство переднего привода, а не
 * настройка. Она же объясняет повадку: под тягой первой сдаётся передняя ось,
 * и машина сносит наружу, а не срывается кормой.
 *
 * Критические повреждения и ожидаемый результат:
 *
 *   - потеря переднего колеса: угол проваливается, тяга остаётся только с
 *     одной стороны и тянет машину в сторону; ехать можно, целиться нельзя;
 *   - потеря заднего колеса: корма садится на щиток, машина едет;
 *   - разрушение платформы пола: машина перестаёт быть одним телом.
 *
 * ── МАСШТАБ ───────────────────────────────────────────────────────────────
 *
 * Массы города НАСТОЯЩИЕ: замер по сцене даёт отношение «масса куска к
 * габаритному объёму на плотность» ровно 1.00 у бетона, кирпича, дерева и
 * асфальта. Единица массы проекта — тонна, единица силы — килоньютон.
 * Раздуты примерно в двести раз только ЛЕТАЮЩИЕ машины (гексакоптер весит
 * 86.5 при пяти с половиной метрах габарита), и это известный запаркованный
 * дефект, а не соглашение мира.
 *
 * Машина живёт в городе и бьётся о городские предметы, поэтому её масса
 * настоящая: 1.33 против 0.17 у медианного кирпичного куска и 0.65 у
 * бетонного. Отсюда и удар получается ударом, а не проездом бульдозера.
 *
 * Ни одна сила ниже не задана абсолютным числом: все они выведены из массы и
 * паспортного ускорения, поэтому смена масштаба мира их не сломает.
 */


// ---------------------------------------------------------------------------
// ГИДРОПНЕВМАТИКА
//
// Подвеска САМОВЫРАВНИВАЮЩАЯСЯ: сколько машину ни грузи, она возвращает
// заданный клиренс. В модели это выражается не отдельным регулятором, а
// посадкой в СЕРЕДИНУ хода при снаряжённой массе — тогда и ход отбоя, и ход
// сжатия остаются машине целиком, чего у обычной пружины не бывает.
//
// Собственная частота при такой жёсткости — около 1.25 Гц. Настоящая машина
// мягче большинства современных, и именно этим известна; ниже опускать нельзя,
// иначе корпус начнёт раскачиваться на каждом торможении.
// ---------------------------------------------------------------------------

export const DS_SUSPENSION_TRAVEL = 0.32;
/** Осадка под снаряжённой массой: ровно половина хода. */
export const DS_STATIC_COMPRESSION = DS_SUSPENSION_TRAVEL / 2;
/** Относительное демпфирование. Мягко, но без раскачки. */
export const DS_DAMPING_RATIO = 0.32;

/**
 * Жёсткость угла, кН/м. Считается из доли веса на этом колесе и требуемой
 * осадки — так число остаётся верным при любой массе и любом масштабе мира.
 */
export function dsCornerStiffness(weightShare: number): number {
  return (DS_MASS * 9.81 * weightShare) / DS_STATIC_COMPRESSION;
}

/** Сопротивление амортизатора угла, кН·с/м, от той же доли веса. */
export function dsCornerDamping(weightShare: number): number {
  const stiffness = dsCornerStiffness(weightShare);
  const cornerMass = DS_MASS * weightShare;
  return 2 * DS_DAMPING_RATIO * Math.sqrt(stiffness * cornerMass);
}


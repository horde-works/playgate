/** Куда смотрит фара при данном угле руля, в авторских осях. */
export function dsHeadlampDirection(
  station: DsHeadlampStation,
  steer: number,
): readonly [number, number] {
  const angle = station.directional ? steer * DS_HEADLAMP_STEER_SHARE : 0;
  const sin = Math.sin(angle);
  const cos = Math.cos(angle);
  // Правый борт выводится из носа тем же произведением, что и в силовой
  // модели (`forward × up`), а не выписывается знаками руками: иначе фара и
  // колесо однажды разъедутся, и заметит это только ночной кадр.
  const length = Math.hypot(DS_NOSE[0], DS_NOSE[2]) || 1;
  const nx = DS_NOSE[0] / length;
  const nz = DS_NOSE[2] / length;
  const sx = -nz;
  const sz = nx;
  return [nx * cos + sx * sin, nz * cos + sz * sin];
}


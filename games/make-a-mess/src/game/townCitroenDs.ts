export const DS_SCENE_ID = "town-boulevard";
export const DS_CLUSTER_ID = "town-boulevard:ds";

/**
 * Живое составное тело дороги. Должно стоять в `compoundClusterDefinitions`
 * рядом с поездом и airborne-кадрами: иначе куски остаются static Intact, а
 * лучи подвески бьют в призрак корпуса на парковке.
 */
export function townDsClusterDefinition(): CompoundKinematicClusterDefinition {
  return {
    id: "town-ds",
    clusterId: DS_CLUSTER_ID,
    origin: dsPoint(0, 0, 0),
    // Колёса опираются ЛУЧАМИ подвески. Если отдать их Rapier-коллайдерами,
    // солвер приклеит машину к асфальту трением, а тяга из пятен контакта
    // ничего не сдвинет.
    contactMemberExcludes: [":wheel:"],
    // ОТКРЫТО: КОЛЁСА НЕ ПОВОРАЧИВАЮТСЯ И НЕ КАТЯТСЯ ВИЗУАЛЬНО.
    //
    // Механизм для этого в проекте есть и он верный — тот самый, которым у
    // дирижабля крутятся винты: артикулированный член, позу которого пишет
    // сам кузов (`independentMemberMatches` + запись позы в системе машины).
    // Дело чисто визуальное: рулю машина слушается и так.
    //
    // Три попытки включить его развалили подвеску, и вот что замерено:
    //   1. луч подвески находит опору в собственном колесе — пробой до
    //      упора на всех четырёх, машина садится в асфальт;
    //   2. кинематическое колесо изнутри арки распирает свой же
    //      динамический кузов — нагрузки по углам расходятся втрое;
    //   3. с исключением своих тел из луча И погашенными группами коллизий
    //      машина всё равно встаёт на две диагональные опоры и висит на
    //      88 мм выше дороги: два колеса видят опору в 0.335 под ступицей,
    //      два в 0.622. Тела колёс при этом существуют и уже кинематические
    //      (тип 2, по одному коллайдеру) — то есть причина НЕ в них.
    //
    // Следующий шаг — не гипотеза, а замер: печатать, во ЧТО попал каждый
    // луч (`hit.collider` и его владельца), а не только расстояние. Без
    // этого числа четвёртая догадка будет стоить столько же, сколько первые
    // три, и так же ничего не даст.
  };
}


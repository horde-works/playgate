/**
 * АРТИКУЛЯЦИЯ ЧЛЕНА КЛАСТЕРА — ТОЛЬКО ДЛЯ РЕНДЕРА
 *
 * Задача: колесо машины обязано поворачиваться за рулём и катиться, оставаясь
 * при этом частью несущего кластера.
 *
 * ── ПОЧЕМУ НЕ ЧЕРЕЗ ТЕЛО ──────────────────────────────────────────────────
 *
 * Напрашивающийся путь — объявить колесо `independentMemberMatches`, как
 * лопасть винта у дирижабля. Тогда кусок получает СВОЁ кинематическое тело с
 * коллайдером, и его позу пишет машина. Для лопасти, торчащей в воздухе, это
 * работает. Для колеса — нет, и это проверено тремя заходами:
 *
 *   1. луч подвески находил опору в собственном колесе — пробой до упора на
 *      всех четырёх, машина садилась в асфальт;
 *   2. кинематическое колесо изнутри арки распирало свой же динамический
 *      кузов — нагрузки по углам расходились втрое;
 *   3. с исключением своих тел из луча И погашенными группами коллизий машина
 *      всё равно вставала на две диагональные опоры и висела в воздухе.
 *
 * Общая причина у всех трёх одна: колесо стоит ВНУТРИ обвода и вплотную к
 * лучу подвески, поэтому любой его коллайдер — помеха. Никакая настройка
 * фильтров этого не лечит, потому что лечить нечего: тело там просто лишнее.
 *
 * ── КАК ЗДЕСЬ ─────────────────────────────────────────────────────────────
 *
 * Колесо остаётся ОБЫЧНЫМ членом кластера: без тела, без коллайдера, контакт
 * за него держит носитель. Меняется ровно одно — матрица, которой его рисуют.
 * `DynamicBreakableWorld` уже собирает позу несомого куска как
 * «поза кластера × собственная поза куска»; сюда вклинивается ещё один
 * поворот ВОКРУГ СОБСТВЕННОГО ЦЕНТРА куска.
 *
 * Физика при этом не может пострадать в принципе: она об этом повороте не
 * знает, потому что знать ей не о чем — тела нет.
 *
 * Ограничение честное: артикуляция чисто визуальная. Повёрнутое колесо не
 * начнёт цеплять бордюр повёрнутым боком. Для колеса это ровно то, что нужно —
 * пятно контакта считает `carDynamics`, и оно уже повёрнуто. Ровно так же и
 * ход стойки: реакцию грунта считает `supportStrut`, а сюда приходит уже
 * посчитанное обжатие, чтобы шток было видно.
 */

/** Поворот члена вокруг собственного центра, радианы, оси — локальные. */
export interface MemberArticulation {
  /** Рыскание: поворот руля. */
  readonly steer: number;
  /** Качение: угол проката колеса. */
  readonly spin: number;
  /**
   * Сдвиг члена относительно авторской позы, в осях КЛАСТЕРА, метры.
   *
   * Ход стойки: шток олео и всё, что висит на нём, ходят вдоль своей оси, а
   * не поворачиваются. Без этого осевшая машина уводила бы нарисованную пятку
   * под грунт — та же мина, на которой уже сидело колесо автомобиля, только
   * там она вылезала на кочках, а здесь вылезает на каждой посадке.
   */
  readonly slide?: readonly [number, number, number];
  /**
   * Поворот вокруг ПРОИЗВОЛЬНОЙ оси, в осях кластера.
   *
   * Руль и прокат колеса живут в осях самого колеса и обходятся `steer`/`spin`.
   * Нога шасси складывается вокруг цапфы — оси, которая куску не принадлежит и
   * с его осями не совпадает. Поворот ВОКРУГ ЧУЖОЙ ОСИ раскладывается на этот
   * поворот вокруг собственного центра и `slide`, который уводит сам центр;
   * считает разложение тот, кто знает цапфу, а рендерер просто складывает.
   */
  readonly turn?: {
    readonly axis: readonly [number, number, number];
    readonly angle: number;
  };
}

const articulations = new Map<string, MemberArticulation>();

/**
 * Задать поворот члена. Вызывается системой машины каждый кадр; ключ — полный
 * id куска, тот же, что у рендерера.
 */
export function setMemberArticulation(
  pieceId: string,
  articulation: MemberArticulation,
): void {
  articulations.set(pieceId, articulation);
}

/** Поворот члена или `undefined`, если он не артикулирован. */
export function getMemberArticulation(
  pieceId: string,
): MemberArticulation | undefined {
  return articulations.get(pieceId);
}

/** Есть ли вообще артикулированные члены: рендерер не платит, пока их нет. */
export function hasMemberArticulations(): boolean {
  return articulations.size > 0;
}

/** Снять артикуляцию: машина уехала из сцены или кусок отвалился. */
export function clearMemberArticulation(pieceId: string): void {
  articulations.delete(pieceId);
}

/** Полная очистка при смене сцены. */
export function clearAllMemberArticulations(): void {
  articulations.clear();
}

/**
 * ПОВОРОТ ЧЛЕНА ВОКРУГ ЧУЖОЙ ОСИ: ОДНА ФОРМУЛА НА ВСЕ ШАРНИРЫ МАШИНЫ.
 *
 * Нога шасси ходит вокруг цапфы, элерон — вокруг петли, лопасть — вокруг вала.
 * Ни одна из этих осей куску не принадлежит и с его центром не совпадает,
 * поэтому поворот раскладывается на две части: вращение вокруг СОБСТВЕННОГО
 * центра, которое делает рендерер, и сдвиг самого центра по дуге. Считает
 * разложение тот, кто знает ось; рендерер просто складывает.
 *
 * Механика та же, что у `strutFoldOffset`, но без единого слова про стойки:
 * шарнир есть шарнир, и второго закона для створки заводить не за что.
 */
export function articulationAboutPivot(
  pivot: readonly [number, number, number],
  axis: readonly [number, number, number],
  angle: number,
  memberCentre: readonly [number, number, number],
): MemberArticulation {
  const length = Math.hypot(axis[0], axis[1], axis[2]) || 1;
  const unit: readonly [number, number, number] = [
    axis[0] / length,
    axis[1] / length,
    axis[2] / length,
  ];
  if (Math.abs(angle) < 1e-9) {
    return { steer: 0, spin: 0, turn: { axis: unit, angle: 0 }, slide: [0, 0, 0] };
  }
  const arm: readonly [number, number, number] = [
    memberCentre[0] - pivot[0],
    memberCentre[1] - pivot[1],
    memberCentre[2] - pivot[2],
  ];
  // Родригес: поворот плеча вокруг оси шарнира.
  const cosine = Math.cos(angle);
  const sine = Math.sin(angle);
  const along = unit[0] * arm[0] + unit[1] * arm[1] + unit[2] * arm[2];
  const crossed: readonly [number, number, number] = [
    unit[1] * arm[2] - unit[2] * arm[1],
    unit[2] * arm[0] - unit[0] * arm[2],
    unit[0] * arm[1] - unit[1] * arm[0],
  ];
  return {
    steer: 0,
    spin: 0,
    turn: { axis: unit, angle },
    slide: [
      arm[0] * cosine + crossed[0] * sine + unit[0] * along * (1 - cosine) - arm[0],
      arm[1] * cosine + crossed[1] * sine + unit[1] * along * (1 - cosine) - arm[1],
      arm[2] * cosine + crossed[2] * sine + unit[2] * along * (1 - cosine) - arm[2],
    ],
  };
}

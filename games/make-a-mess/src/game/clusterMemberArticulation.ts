/**
 * АРТИКУЛЯЦИЯ ЧЛЕНА КЛАСТЕРА — ТОЛЬКО ДЛЯ РЕНДЕРА
 *
 * Задача: колесо машины обязано поворачиваться за рулём и катиться, оставаясь
 * при этом частью несущего кластера.
 *
 * ── ПОЧЕМУ НЕ ЧЕРЕЗ ТЕЛО ──────────────────────────────────────────────────
 *
 * Напрашивающийся путь — объявить колесо `independentMemberMatches`, как
 * лопасть винта у дирижабля. Тогда кусок получает СВОЁ кинематическое тело с
 * коллайдером, и его позу пишет машина. Для лопасти, торчащей в воздухе, это
 * работает. Для колеса — нет, и это проверено тремя заходами:
 *
 *   1. луч подвески находил опору в собственном колесе — пробой до упора на
 *      всех четырёх, машина садилась в асфальт;
 *   2. кинематическое колесо изнутри арки распирало свой же динамический
 *      кузов — нагрузки по углам расходились втрое;
 *   3. с исключением своих тел из луча И погашенными группами коллизий машина
 *      всё равно вставала на две диагональные опоры и висела в воздухе.
 *
 * Общая причина у всех трёх одна: колесо стоит ВНУТРИ обвода и вплотную к
 * лучу подвески, поэтому любой его коллайдер — помеха. Никакая настройка
 * фильтров этого не лечит, потому что лечить нечего: тело там просто лишнее.
 *
 * ── КАК ЗДЕСЬ ─────────────────────────────────────────────────────────────
 *
 * Колесо остаётся ОБЫЧНЫМ членом кластера: без тела, без коллайдера, контакт
 * за него держит носитель. Меняется ровно одно — матрица, которой его рисуют.
 * `DynamicBreakableWorld` уже собирает позу несомого куска как
 * «поза кластера × собственная поза куска»; сюда вклинивается ещё один
 * поворот ВОКРУГ СОБСТВЕННОГО ЦЕНТРА куска.
 *
 * Физика при этом не может пострадать в принципе: она об этом повороте не
 * знает, потому что знать ей не о чем — тела нет.
 *
 * Ограничение честное: артикуляция чисто визуальная. Повёрнутое колесо не
 * начнёт цеплять бордюр повёрнутым боком. Для колеса это ровно то, что нужно —
 * пятно контакта считает `carDynamics`, и оно уже повёрнуто.
 */

/** Поворот члена вокруг собственного центра, радианы, оси — локальные. */
export interface MemberArticulation {
  /** Рыскание: поворот руля. */
  readonly steer: number;
  /** Качение: угол проката колеса. */
  readonly spin: number;
}

const articulations = new Map<string, MemberArticulation>();

/**
 * Задать поворот члена. Вызывается системой машины каждый кадр; ключ — полный
 * id куска, тот же, что у рендерера.
 */
export function setMemberArticulation(
  pieceId: string,
  articulation: MemberArticulation,
): void {
  articulations.set(pieceId, articulation);
}

/** Поворот члена или `undefined`, если он не артикулирован. */
export function getMemberArticulation(
  pieceId: string,
): MemberArticulation | undefined {
  return articulations.get(pieceId);
}

/** Есть ли вообще артикулированные члены: рендерер не платит, пока их нет. */
export function hasMemberArticulations(): boolean {
  return articulations.size > 0;
}

/** Снять артикуляцию: машина уехала из сцены или кусок отвалился. */
export function clearMemberArticulation(pieceId: string): void {
  articulations.delete(pieceId);
}

/** Полная очистка при смене сцены. */
export function clearAllMemberArticulations(): void {
  articulations.clear();
}

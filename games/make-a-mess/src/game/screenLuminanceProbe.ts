/**
 * Замер яркости ГОТОВОГО кадра в заданных точках экрана.
 *
 * Нужен адаптивному цвету телеметрии (вердикт Igor: ни плашек, ни обводок —
 * обычный текст контрастного к фону цвета). DOM-панель знает, ГДЕ стоят её
 * строки; кадр знает, ЧТО за ними. Мост — этот стор: панель кладёт точки в
 * client-координатах, семплер внутри Canvas читает готовый кадр после
 * пост-цепочки и возвращает воспринимаемую яркость 0..1.
 *
 * Чтение — sRGB-байты дефолтного фреймбуфера, то есть ровно то, что видит
 * глаз после тонмапа. Семплер тикает редко (throttle у него), точки — 1×1:
 * цена синхронного чтения — микросекунды раз в четверть секунды.
 */

export interface ScreenLuminancePoint {
  /** clientX центра интересующего текста. */
  readonly x: number;
  /** clientY центра интересующего текста. */
  readonly y: number;
}

export const screenLuminanceProbe = {
  requests: new Map<string, ScreenLuminancePoint>(),
  /** Воспринимаемая яркость фона 0..1 по ключам запросов. */
  results: new Map<string, number>(),
  /** Растёт с каждым завершённым проходом семплера. */
  version: 0,
};

/** Rec. 709 из sRGB-байтов — воспринимаемая, без линеаризации нарочно. */
export function luminanceFromBytes(
  r: number,
  g: number,
  b: number,
): number {
  return (0.2126 * r + 0.7152 * g + 0.0722 * b) / 255;
}

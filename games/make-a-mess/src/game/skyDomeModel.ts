/**
 * Закон амортизированного купола неба.
 *
 * Небо направленно: его радианс зависит от направления взгляда и состояния
 * атмосферы, но не от точки, из которой смотрят (параллакс от шагов игрока
 * нулевой). Значит марш воздуха и палубы не обязан выполняться на каждом
 * пикселе каждого кадра — он выполняется в кубокарту, грань за граню, а кадр
 * читает её одной выборкой. Это амортизация, а не спуск качества: грани
 * маршируются ВСЕГДА на авторском максимуме (quality 2), сколько бы губернатор
 * ни срезал живой марш.
 *
 * Когда солнце движется (переход по KeyN — в обычной игре солнце стоит),
 * купол честно уступает место живому маршу: кэш с шестикадровой разверткой
 * показал бы солнце, скачущее между гранями. Остановилось — шесть кадров на
 * полную перекраску, и кадр снова платит за небо одну выборку.
 *
 * Дрейф палубы (мирам с coverage > 0) перекрашивает купол непрерывно по одной
 * грани за кадр: полный оборот за 6 кадров, за которые облако уходит меньше
 * чем на полметра мира — глазу нечем заметить шов между гранями.
 */

/**
 * Рубильник честного A/B: false возвращает живой марш на каждый пиксель
 * каждый кадр (поведение до кэша), не трогая остальной конвейер.
 */
export const SKY_DOME_CACHE_ENABLED = true;

/**
 * Сторона грани кубокарты. 512 px на 90° — 5.7 px/градус: солнечный диск
 * (0.53°) занимает ~3 текселя и после блума читается диском, кучевая куча в
 * несколько градусов — десятки текселей. Экранная плотность неба при fov 72°
 * на 1600 px — 22 px/градус, то есть купол мягче экрана вчетверо; мягкость
 * уходит в облака и градиенты, которым она к лицу, а не в геометрию.
 */
export const DOME_FACE_SIZE = 512;

/** Граней за кадр при перекраске; больше одной — уже не амортизация. */
export const DOME_FACES_PER_FRAME = 1;

export const DOME_FACE_COUNT = 6;

/**
 * Сколько ПОЛНЫХ оборотов купол перекрашивается после любой инвалидации,
 * прежде чем чистому небу разрешено замереть. Один оборот недостаточен:
 * первые кадры входа в мир несут переходные состояния (снап солнца,
 * достройка таблиц, грубый режим соседней PMREM-печки), и купол, замерший
 * по первому обороту, замораживал их навсегда — город получал чёрный сектор
 * неба до первого движения солнца.
 */
export const DOME_SETTLE_CYCLES = 3;

/**
 * Каждый который кадр красится одна грань, по gpuQuality 0/1/2. Спуск
 * оси — ТЕМП перекраски, а не качество марша: грань всегда авторский
 * максимум. На полу (страйд 3) полный оборот занимает 18 кадров — палуба
 * за это время уходит меньше чем на градус, шов глазу не виден.
 */
export const DOME_REPAINT_STRIDES = [3, 2, 1] as const;

/**
 * Бакет направления солнца — тот же закон, что у PMREM-перепечки ambient:
 * перекраска купола по чистому небу (без палубы) нужна только когда солнце
 * сдвинулось заметно для глаза.
 */
export function sunDirectionBucket(x: number, y: number, z: number): string {
  return `${Math.round(x * 10)}:${Math.round(y * 14)}:${Math.round(z * 10)}`;
}

/**
 * Нужна ли куполу непрерывная перекраска. Палуба дрейфует по ветру — да;
 * чистое небо статично между сдвигами солнца — нет.
 */
export function domeNeedsContinuousRepaint(coverage: number): boolean {
  return coverage > 0;
}

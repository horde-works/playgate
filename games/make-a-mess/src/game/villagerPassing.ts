/**
 * ЗАКОН РАСХОЖДЕНИЯ ПЕШЕХОДОВ.
 *
 * Прежнее правило смотрело на ТЕКУЩЕЕ расстояние: соседи ближе 1.3 м, из них
 * те, кто впереди, — и человек брал в сторону. У него три беды, и все видны
 * глазом:
 *
 *  1. **1.3 м — это радиус тела, а не радиус расхождения.** Живые люди правят
 *     траекторию за несколько метров до встречи, пока манёвр ещё стоит
 *     полшага; здешние сворачивали в последний момент.
 *  2. **Расстояние не отличает встречу от попутного хода.** Двое, идущие рядом
 *     в одну сторону, никогда не столкнутся, но по расстоянию неразличимы с
 *     теми, кто идёт лоб в лоб, — и потому расталкивались без причины.
 *  3. **Знак поправки брался от текущего положения** соседа. Стоит соседу
 *     пересечь осевую — знак переворачивается, и оба начинают дёргаться.
 *
 * Всё три лечит одна замена: судить не по расстоянию СЕЙЧАС, а по **промаху в
 * точке наибольшего сближения**. Это же и есть та величина, которой пользуется
 * человек: на курсе столкновения пеленг не меняется, и именно неизменность
 * пеленга, а не близость, читается как «сейчас столкнёмся».
 *
 * И вторая половина задачи — СОГЛАСОВАННОСТЬ. Если оба уступают одинаково,
 * получается зеркальный танец. В жизни порядок прохода решается рано и почти
 * не пересматривается: кто приходит к точке пересечения позже, тот и уступает
 * больше. Обе стороны считают одно и то же и приходят к согласию, ничего друг
 * другу не сообщая.
 *
 * Статусы чисел — в `docs/village-inhabitants-lessons.md` §8.2.
 */

/** Кто угодно, кто движется по земле: житель, а в будущем и не только. */
export interface Walker {
  readonly x: number;
  readonly z: number;
  /** Направление корпуса; скорость идёт вдоль него. */
  readonly yaw: number;
  readonly speed: number;
}

/**
 * Насколько вперёд человек смотрит по времени. Порядок величины измерен
 * (пешеходы начинают править траекторию за секунды до сближения, а не за
 * сантиметры), точное число — **допущение**.
 */
export const PASSING_HORIZON = 3;

/**
 * Дальше этого соседей не рассматриваем вовсе — но это ОПТИМИЗАЦИЯ, а не
 * порог поведения: границу обязан задавать горизонт по времени, иначе закон
 * включается скачком там, где сосед попал в радиус. Взято с запасом: двое
 * встречных сближаются со скоростью ~2.6 м/с, за горизонт в 3 с это 7.8 м.
 */
export const PASSING_LOOK_AHEAD = 10;

/**
 * За сколько секунд до горизонта поправка набирает полную силу. Без этого
 * ввода закон снова включается скачком — замер поймал прыжок совета на
 * 0.32 рад за один кадр, а это то же дёрганье, только загнанное в край.
 */
export const PASSING_FADE = 1;

/**
 * Промах, который человека устраивает. Ниже — начинает расходиться, выше —
 * не трогает вовсе. **Допущение**, откалибровано по обиходной дистанции между
 * незнакомыми людьми (порядка метра).
 */
export const PASSING_COMFORT = 1;

/**
 * Раньше этого срока манёвр уже не размазать: остаток времени, за который
 * поправка обязана быть набрана. Держит закон от взрыва в последний миг.
 */
export const PASSING_MIN_TIME = 0.5;

/** Предел суммарной поправки: иначе в толчее у колодца человек рыскает. */
export const PASSING_CAP = 0.5;

/**
 * Доля усилия того, кто приходит к точке пересечения ПЕРВЫМ. Не ноль: в жизни
 * поправку вносят оба, просто по-разному. **Допущение.**
 */
export const YIELD_EARLY_SHARE = 0.35;

/** Насколько уступающий сбавляет ход. Допущение. */
export const PASSING_SLOW = 0.18;

function clamp01(value: number): number {
  return value < 0 ? 0 : value > 1 ? 1 : value;
}

/** Двумерное векторное произведение: знак говорит, с какой стороны обход. */
function cross(ax: number, az: number, bx: number, bz: number): number {
  return ax * bz - az * bx;
}

export interface PassingAdvice {
  /** Поправка к желаемому курсу, радианы. */
  readonly steer: number;
  /** Во сколько раз сбавить ход: 1 — не сбавлять. */
  readonly pace: number;
  /** Насколько срочно расходиться, 0..1. Для замеров. */
  readonly urgency: number;
}

const CALM: PassingAdvice = { steer: 0, pace: 1, urgency: 0 };

/**
 * Куда и насколько отвернуть, чтобы разойтись со всеми, с кем сходишься.
 *
 * Чистая функция: ни состояния, ни памяти, ни случайности. Сглаживание во
 * времени — забота вызывающего (симуляция ведёт поправку низкочастотно, иначе
 * дёрганье вернётся через заднюю дверь).
 */
export function passingAdvice(me: Walker, others: Iterable<Walker>): PassingAdvice {
  if (me.speed <= 1e-3) {
    // Стоящий никого не обходит: обходят его.
    return CALM;
  }
  const myVx = Math.sin(me.yaw) * me.speed;
  const myVz = Math.cos(me.yaw) * me.speed;
  // Правая рука в той же системе, в которой живёт рыскание.
  const rightX = Math.cos(me.yaw);
  const rightZ = -Math.sin(me.yaw);

  let steer = 0;
  let worst = 0;
  let yielding = 0;

  for (const other of others) {
    const rx = other.x - me.x;
    const rz = other.z - me.z;
    const range = Math.hypot(rx, rz);
    if (range > PASSING_LOOK_AHEAD || range < 1e-4) {
      continue;
    }
    const otherVx = Math.sin(other.yaw) * other.speed;
    const otherVz = Math.cos(other.yaw) * other.speed;
    const vx = otherVx - myVx;
    const vz = otherVz - myVz;
    const closing = vx * vx + vz * vz;
    if (closing < 1e-6) {
      // Идут ровно вместе и с одной скоростью — сближения нет вовсе.
      continue;
    }
    // Момент наибольшего сближения. Отрицательный — уже разошлись.
    let when = -(rx * vx + rz * vz) / closing;
    if (when < 0) {
      continue;
    }
    when = Math.min(when, PASSING_HORIZON);
    const missX = rx + vx * when;
    const missZ = rz + vz * when;
    const miss = Math.hypot(missX, missZ);
    if (miss >= PASSING_COMFORT) {
      // Разойдёмся и так. ИМЕННО ЭТА ветка убирает возню попутчиков: у идущих
      // рядом в одну сторону промах не меняется, и трогать их незачем.
      continue;
    }

    // СКОЛЬКО НЕ ХВАТАЕТ И СКОЛЬКО ЕСТЬ ВРЕМЕНИ — из этих двух чисел поправка
    // считается, а не подбирается. Не хватает `deficit` метров бокового
    // просвета, а набрать их надо за `when` секунд; отсюда нужная боковая
    // скорость, а из неё — угол отворота.
    //
    // Так закон получается сам собой ранним и мягким: за три метра до встречи
    // времени много, и хватает малого доворота; если же прозевать, времени
    // остаётся мало и доворот растёт. Прежняя версия душила срочность
    // множителем времени и оттого просыпалась в последний момент — замер:
    // один микро-толчок на 0.002 рад за всю встречу.
    // Ввод у горизонта плавный: на самой границе поправка нулевая и нарастает
    // по мере сближения. Иначе граница сама становится причиной движения.
    const fade = clamp01((PASSING_HORIZON - when) / PASSING_FADE);
    if (fade <= 0) {
      continue;
    }
    const deficit = PASSING_COMFORT - miss;
    const urgency = clamp01(deficit / PASSING_COMFORT) * fade;
    const rate = deficit / Math.max(when, PASSING_MIN_TIME);
    const turn = Math.asin(clamp01(rate / me.speed) * 0.99) * fade;

    // КТО УСТУПАЕТ. Ищем точку, где пересекаются их пути, и время, за которое
    // каждый до неё доходит. Обе стороны считают одно и то же, поэтому
    // приходят к согласию, ничего друг другу не сообщая.
    const den = cross(myVx, myVz, otherVx, otherVz);
    let share = 1;
    let side: number;
    if (Math.abs(den) > 1e-4) {
      const mine = cross(rx, rz, otherVx, otherVz) / den;
      const theirs = cross(rx, rz, myVx, myVz) / den;
      // Первым приходит тот, у кого меньше время: он держит курс, второй
      // уступает. Позади себя пропускать удобнее, чем перед собой.
      share = mine > theirs ? 1 : YIELD_EARLY_SHARE;
      // Обходим ЗА КОРМОЙ: сторона, куда сосед НЕ идёт.
      const astern = -(otherVx * rightX + otherVz * rightZ);
      side = Math.sign(astern) || 1;
    } else {
      // Пути параллельны: лоб в лоб или обгон. Оба берут вправо от себя — это
      // работает именно потому, что правило общее: разойдутся левыми плечами.
      side = 1;
    }

    steer += side * turn * share;
    worst = Math.max(worst, urgency);
    if (share > YIELD_EARLY_SHARE) {
      yielding = Math.max(yielding, urgency);
    }
  }

  if (steer === 0 && worst === 0) {
    return CALM;
  }
  return {
    steer: Math.max(-PASSING_CAP, Math.min(PASSING_CAP, steer)),
    pace: 1 - PASSING_SLOW * yielding,
    urgency: worst,
  };
}

import assert from "node:assert/strict";
import test from "node:test";
import { runDuel } from "./air-combat-rig.mjs";

/**
 * КОНВЕРТ БРОСКА: ИЗ КАКИХ СОСТОЯНИЙ ТЕЛА АТАКА ВООБЩЕ УДАЁТСЯ.
 *
 * Зверь не выбирает между «броситься» и «красться» по настроению. Он проверяет
 * одно: сработает ли прыжок ИЗ ТОЙ ПОЗЫ, в которой он сейчас. Хватает тела —
 * прыгает немедленно; не хватает — крадётся, и подкрадывание есть не терпение,
 * а приведение тела в состояние, из которого прыжок возможен.
 *
 * Значит, прежде связок надо знать конверты. Здесь они и снимаются: машину
 * ставят в заданное состояние ОТНОСИТЕЛЬНО ЦЕЛИ — ход, превышение, ракурс — и
 * смотрят, состоится ли выстрел и чем кончится для тела.
 *
 * Полная развёртка (27 состояний) снималась пробником; сюда взяты те шесть,
 * которые держат её форму. Гонять все двадцать семь в наборе незачем: это
 * четыре минуты симуляции ради чисел, которые не меняются от правки кода в
 * другом месте.
 */

const RANGE = 80;
const strike = (aspect, speed, above) =>
  runDuel({
    seconds: 9,
    target: "vx8",
    entry: { speed, above, range: RANGE, aspect },
  });

const HEAD_ON = 0;
const ACROSS = Math.PI / 2;

const headOnLevel = strike(HEAD_ON, 16, 0);
const headOnHigh = strike(HEAD_ON, 16, 38);

test("ВСТРЕЧНЫЙ БРОСОК С ОДНОЙ ВЫСОТЫ — лучший, какой у этой машины есть", () => {
  // Полсекунды до первого выстрела и десятки попаданий: сближение равно сумме
  // скоростей, ракурс наибольший, доворачивать нечего.
  assert.ok(
    headOnLevel.firstShotAt !== null && headOnLevel.firstShotAt < 1.5,
    `первый выстрел на ${headOnLevel.firstShotAt}-й секунде`,
  );
  assert.ok(
    headOnLevel.cannonHits + headOnLevel.rocketHits > 10,
    `всего ${headOnLevel.cannonHits + headOnLevel.rocketHits} попаданий`,
  );
});

test("ПРЕВЫШЕНИЕ БОЛЬШЕ НЕ ОТМЕНЯЕТ БРОСОК — клетка была не в машине", () => {
  // ЗДЕСЬ ДВАЖДЫ СТОЯЛ ВЫВОД, И ОБА РАЗА ЕГО ОПРОВЕРГАЛ ЗАМЕР. Оставляю всю
  // цепочку: она про то, как свойство КОДА выдают за свойство МАШИНЫ.
  //
  // Сперва я вывел «высота → ход»: сорок метров превышения дают на пикировании
  // 28 м/с, которых у мотора нет, — и записал пикирование в ударные кандидаты.
  //
  // Потом замер это опроверг: с восемнадцати метров выстрел уезжал на 5.4-ю
  // секунду, с тридцати восьми не случался вовсе за девять, и машина выходила
  // НИЖЕ станции, проскочив цель по вертикали. Объяснение я взял из самого же
  // автомата: «ствол связан с корпусом, вертикальное наведение делается
  // ВЫСОТОЙ, значит превышение надо сперва потратить».
  //
  // И вот это объяснение было неверным — оно описывало не машину, а пробел в
  // боевом модуле. Курс у него был парой чисел `[x, z]`, наводило одно
  // рыскание, и вертикальную составляющую ошибки он видел, но исправить не мог
  // ничем. Шесть высотных отказов на полной развёртке были ЕГО отказами.
  //
  // Как только автомат научился задавать позу (`airCombatPosture.ts`), те же
  // самые входы дали:
  //
  //     превышение   было              стало
  //     0 м          выстрел 0.5 с     0.45 с
  //     18 м         5.4 с             1.8 с
  //     38 м         НЕ СОСТОЯЛСЯ      2.3 с, и цель поражена
  //
  // Машина при этом не спускается к ярусу цели: она встаёт стволом вниз — до
  // 67° ниже горизонта — и работает с превышения, НАБИРАЯ высоту. Вес на такой
  // позе держат тоннели реверсом, и это не трюк, а разложение (там же).
  assert.ok(
    headOnHigh.firstShotAt !== null && headOnHigh.firstShotAt < 4,
    `с превышения выстрел на ${headOnHigh.firstShotAt}-й секунде`,
  );
  assert.ok(
    headOnHigh.cannonHits + headOnHigh.rocketHits > 0,
    "и он обязан попадать, а не просто состояться",
  );
  // ГЛАВНОЕ ЧИСЛО ЗДЕСЬ — НЕ ВЫСТРЕЛ, А ЯРУС НА ВЫХОДЕ. Прежде высокий вход
  // кончался НИЖЕ ровного: машина тратила превышение, чтобы подставить свою
  // наклонённую ось. Теперь тратить его незачем, и она его сохраняет.
  assert.ok(
    headOnHigh.exitHeight > headOnLevel.exitHeight + 30,
    `высокий вход обязан кончиться ВЫШЕ ровного: ${headOnHigh.exitHeight.toFixed(0)} против ${headOnLevel.exitHeight.toFixed(0)}`,
  );
  // А вот вывод про пикирование остаётся в силе и к клетке отношения не имел:
  // оно покупает ВСТРЕЧУ с тем, кого иначе не догнать, и это про сближение, а
  // не про бросок.
});

test("ПОПЕРЕЧНЫЙ ВХОД ХУЖЕ БЬЁТ, НО ЛУЧШЕ ПРИЗЕМЛЯЕТСЯ", () => {
  // Зверь, приземлившийся плохо, — мёртвый зверь. Связка ценна не только тем,
  // что попала, но и тем, в каком состоянии оставила тело.
  const across = strike(ACROSS, 16, 18);
  assert.ok(
    across.firstShotAt !== null,
    "поперечный вход обязан давать выстрел",
  );
  // Выходит выше и не проскакивает: дистанция к цели остаётся рабочей.
  assert.ok(
    across.exitHeight > 8,
    `вышел на ${across.exitHeight.toFixed(0)} м — потерял ярус`,
  );
  assert.ok(
    across.exitRange > 30 && across.exitRange < RANGE,
    `вышел на ${across.exitRange.toFixed(0)} м от цели`,
  );
});

test("БОЛЬШИНСТВО СОСТОЯНИЙ ПО СРЕДСТВАМ: зверь чаще бросается, чем крадётся", () => {
  // Прямой ответ на вопрос «от чего кошка выбирает». Не от характера: от того,
  // хватает ли тела. Полная развёртка дала 21 состояние из 27 — то есть
  // подкрадывание должно быть исключением, а не повадкой.
  //
  // И все шесть отказов — ВЫСОТНЫЕ. Значит правило простое и проверяемое:
  // бросок отменяет не дальность и не ракурс, а нерастраченное превышение.
  const sampled = [
    strike(HEAD_ON, 21, 0),
    strike(ACROSS, 10, 0),
    headOnLevel,
    headOnHigh,
  ];
  const afforded = sampled.filter((run) => run.firstShotAt !== null).length;
  assert.ok(
    afforded >= 3,
    `по средствам только ${afforded} состояния из ${sampled.length}`,
  );
});

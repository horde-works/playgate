/**
 * Один прогон на все утверждения ниже: дуэль в полтораста секунд стоит дорого,
 * а вопросы к ней разные и независимые.
 */
const yaqui = runDuel({ seconds: 150, target: "vx8" });

test("НЕБО ПОКРЫВАЕТ ВСЁ, ЧТО ЛЕТИТ, — и дальше всех летит промах", () => {
  console.log(`
[дуэль: RAX-8 против VX-8]
  ${summarise(yaqui)}
`);
  // Купол рисуется конечным радиусом; вышедшее за него оказывается нарисовано
  // на пустоте. Предел задаёт НЕ машина: ракета, не нашедшая цели, летит, пока
  // не кончится взрыватель, — 173 м от точки пуска, где бы та ни случилась.
  assert.ok(
    yaqui.reachRockets > yaqui.reachMachines,
    `ракеты (${yaqui.reachRockets.toFixed(0)} м) не обогнали машины (${yaqui.reachMachines.toFixed(0)} м) — замер подозрителен`,
  );
  assert.ok(
    yaqui.reachRockets < RANGE_SKY_RADIUS,
    `ракеты уходят на ${yaqui.reachRockets.toFixed(0)} м при небе ${RANGE_SKY_RADIUS} м`,
  );
  assert.ok(
    yaqui.reachMachines < RANGE_SKY_RADIUS,
    `машины уходят на ${yaqui.reachMachines.toFixed(0)} м при небе ${RANGE_SKY_RADIUS} м`,
  );
});

test("СОСЕД — ЦЕЛЬ ДРУГОГО КЛАССА, а не тот же гость побыстрее", () => {
  const guest = runDuel({ seconds: 150, target: "hx6" });
  // Разница обязана быть в ИСХОДЕ, а не в оттенках. Гость города сбивается за
  // сорок с небольшим секунд; соседняя боевая машина переживает все полтораста.
  assert.notEqual(guest.outcome, "survived", "гость обязан быть сбит");
  assert.equal(
    yaqui.outcome,
    "survived",
    "сосед перестал переживать бой — это хорошая новость и повод переписать утверждение",
  );
});

test("ОХОТНИК НЕ СТОИТ НА СТАНЦИИ, пока цель в воздухе", () => {
  // ЭТО УТВЕРЖДЕНИЕ ЗАМЕНИЛО СВОЮ ПРОТИВОПОЛОЖНОСТЬ, и историю стоит помнить.
  //
  // Пока тело вели в саму цель, погоня за тем, кто быстрее, не сходилась
  // никогда: RAX-8 простаивал СТО ПЯТЬ секунд из полутораста, а прежняя
  // редакция этого теста закрепляла безнадёжность как факт — с припиской, что
  // её исправление будет поводом переписать утверждение. Оно и вышло.
  //
  // Лечение — одна величина: упреждение тела берётся не меньшим, чем
  // упреждение прицела, и равным времени встречи, когда то больше. Погоня
  // превратилась во встречу, станция обнулилась, заходов стало вчетверо
  // больше, а первое попадание пришло на пятой секунде вместо двадцать первой.
  const stationSeconds = yaqui.modeSeconds.station ?? 0;
  assert.ok(
    stationSeconds < yaqui.seconds * 0.05,
    `на станции ${stationSeconds.toFixed(0)} из ${yaqui.seconds.toFixed(0)} с — охотник снова ждёт вместо того, чтобы охотиться`,
  );
  assert.ok(
    yaqui.passes >= 15,
    `заходов всего ${yaqui.passes}: бой перестал быть непрерывным`,
  );
  assert.ok(
    yaqui.firstBloodAt !== null && yaqui.firstBloodAt < 12,
    `первое попадание на ${yaqui.firstBloodAt}-й секунде`,
  );
});

test("ПОД ОГНЁМ ЦЕЛЬ ВСЁ ЕЩЁ КРУТИТ СВОИ НОМЕРА — и это проверяемо", () => {
  // Прежде VX-8 не отрабатывал в бою НИ ОДНОГО номера: к моменту, когда номер
  // наступал по трассе, машина была уже без колец, и ворота отказывали ей
  // поимённо — «недобор власти». Ворота были правы; неправ был бой, который
  // ломал цель за двадцать секунд, ничего при этом не добивая.
  //
  // Теперь охотник работает непрерывно, но и цель доживает до своих номеров:
  // замер даёт семь-восемь фигур за полтораста секунд, включая оба кульбита.
  const keys = yaqui.targetFigures.map((entry) => entry.key);
  assert.ok(
    keys.length >= 5,
    `цель отработала ${keys.length} номеров: ${keys.join(", ") || "ни одного"}`,
  );
  assert.ok(
    keys.some((key) => key.startsWith("kulbit")),
    "кульбит обязан состояться под огнём — иначе его не увидит никто",
  );
  // А ворота остаются воротами: когда власть просядет, номер не начнётся, и
  // причина будет названа, а не проглочена.
  assert.ok(
    yaqui.targetSkips.every((reason) => /власти|высоты|ход мал|неба/.test(reason)),
    `пропуски по неизвестной причине: ${[...new Set(yaqui.targetSkips)].join("; ")}`,
  );
});

test("СУДЬБА ЖЕРТВЫ: соседа добивают, но за сотни секунд, а не за десятки", () => {
  // ЗАМЕР ДО КОНЦА (пробник, 400 с): VX-8 всё-таки гибнет — на 393.6-й секунде,
  // после 146 заходов, 305 выстрелов пушки и 57 ракет. Гость города при том же
  // охотнике сваливается за 22 секунды в два захода.
  //
  // Восемнадцатикратная разница — не про броню и не про толщину лопастей: у
  // VX-8 их ВОСЕМЬ против сорока четырёх у RAX-8, и они тоньше (0.028 против
  // 0.048). Разница в том, что валит машину: не потери кусков, а выход центра
  // масс за оболочку уцелевших точек тяги. У широкой шестикольцевой машины для
  // этого надо убить два кольца в нужных местах, а обязательные куски канала
  // сидят в тоннелях.
  //
  // Здесь проверяется только форма — что за полтораста секунд сосед ещё жив, —
  // потому что четырёхминутный прогон в наборе стоит дороже, чем сообщает.
  assert.equal(yaqui.outcome, "survived");
  // ЧИСЛО СНЯТЫХ КУСКОВ ПЕРЕПИСАНО ПОД ДРУГОЙ ПРИЦЕЛ, и это не послабление.
  //
  // Прежде здесь стояло «больше двадцати за полтораста секунд», и стояло по
  // замеру: наводка выбирала КОНКРЕТНУЮ ещё живую гондолу по сумме «потеря
  // соседей минус цена доворота». Вердикт Igor снял этот способ целиком —
  // стрелок читает паспорт цели и бьёт в уязвимую ЗОНУ примерно, а не
  // выискивает уцелевшие гондолы, — и вместе со способом ушло его число.
  //
  // Против ducted-соседа зона садится на корпус между тоннелями, и дротик там
  // почти ничего не уносит: работает не он, а радиус поражения ракеты. Восемь
  // кусков за полтораста секунд против двадцати пяти — и ровно тот же вердикт
  // по судьбе, потому что судьбу решает не счёт кусков, а выход центра масс за
  // оболочку уцелевших точек тяги.
  assert.ok(
    yaqui.rocketBladeKills > 5,
    `с соседа снято всего ${yaqui.rocketBladeKills} кусков`,
  );
});

test("РАБОТАЕТ РАКЕТА, А НЕ ПУШКА: судьбу решает боезапас, а не ствол", () => {
  // Против соседа пушка почти бесполезна, и это меняет весь ритм охоты: под
  // держит шесть ракет и снаряжается полминуты, значит большую часть боя
  // охотник ходит фактически безоружным.
  //
  // Отсюда и «пустой под — поведение»: зверь, которому нечем бить, обязан не
  // улетать, а висеть рядом. Замер на 400 с: 57 ракет за 394 секунды — это
  // девять с половиной снаряжений, то есть почти пять минут ожидания.
  // КРАТНОСТЬ УБРАНА, ПРЕВОСХОДСТВО ОСТАВЛЕНО — по той же причине, что и число
  // выше. Уязвимая зона садится на корпус, дротик начал уносить хоть что-то
  // оттуда (четыре куска против одного), и разрыв сократился с двадцати пяти к
  // одному до восьми к четырём. Держать здесь конкретную кратность значило бы
  // сторожить не утверждение, а замер: она села ровно на границу «вдвое», и
  // любой шаг в наводке будет ронять тест, ничего при этом не сообщая.
  //
  // Утверждение же уцелело в том виде, в каком оно что-то значит: против соседа
  // судьбу решает под, а не ствол, и весь ритм охоты держат тридцать секунд
  // снаряжения.
  assert.ok(
    yaqui.rocketBladeKills > yaqui.cannonBladeKills,
    `ракеты сняли ${yaqui.rocketBladeKills}, пушка ${yaqui.cannonBladeKills} — ствол внезапно стал решать`,
  );
});

test("СУДЬБА ОХОТНИКА: он выходит ЦЕЛЫМ — и это приговор стенду, а не ему", () => {
  // Власть на конец боя единица: по нему не попали ни разу. И не могли — VX-8
  // вооружён и объявлен чужим кланом, но боевого пилота у него нет: он летает
  // свою показательную программу, пока его расстреливают.
  //
  // То есть это не дуэль, а казнь, и все числа выше надо читать с этой
  // поправкой. Настоящая судьба обоих начнётся тогда, когда жертва научится
  // отвечать.
  assert.equal(
    yaqui.exitAuthority,
    1,
    "в охотника попали — значит жертва отвечает, и утверждение пора переписать",
  );
  // А пока — единственное, что она делает под огнём, это ЛЕТАЕТ СВОЮ ПРОГРАММУ.
  // Шестнадцать фигур за четыре минуты обстрела: машина выступает, пока с неё
  // сбивают куски.
  assert.ok(
    yaqui.targetFigures.length >= 5,
    `под огнём отработано ${yaqui.targetFigures.length} номеров`,
  );
});

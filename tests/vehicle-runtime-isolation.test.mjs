import assert from "node:assert/strict";
import test from "node:test";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

/**
 * РАНТАЙМ НЕ ЗНАЕТ ИМЁН МАШИН.
 *
 * `VehicleFrameSystem` — общий покадровый контур: он ведёт любую машину, у
 * которой есть паспорт, и не имеет права ветвиться по тому, ЧЬЯ она. Способность
 * объявляется паспортом — `armament` объявляет вооружение, `combatStation`
 * объявляет сторожевой пост, — и движок спрашивает про способность, а не про имя.
 *
 * Сторож нужен потому, что нарушение этого правила не выглядит нарушением.
 * Импортировать константу конкретной карты дешевле, чем завести поле в паспорте,
 * и каждый раз это выглядит как «мелочь на один случай». Так в контур приехали
 * три числа полигона Tonkawa: радиус, высота и ход сторожевой орбиты, — и
 * движок начал знать разметку одной карты.
 *
 * Тест намеренно ЗАКРЕПЛЯЕТ И ДОЛГ, а не только достигнутое: имена, которые в
 * контуре ещё остались, перечислены поимённо, и список обязан совпадать точно.
 * Новое имя уронит тест; выплата долга тоже уронит — и это правильно, потому
 * что тогда строку из списка надо вычеркнуть руками.
 */

const RUNTIME = fileURLToPath(
  new URL(
    "../games/make-a-mess/src/game/VehicleFrameSystem.tsx",
    import.meta.url,
  ),
);

const source = readFileSync(RUNTIME, "utf8");

/** Имена машин и миров, которые в этом проекте уже заведены. */
const MACHINE_WORDS =
  /[A-Za-z_]*([Hh]exacopter|HEXACOPTER|[Ss]kyTrain|SKY_TRAIN|[Ll]ongship|LONGSHIP|[Dd]rakkar|DRAKKAR|[Ss]kat\b|SKAT)[A-Za-z_]*/g;

test("боевой контур не ветвится по имени машины и не знает разметки карты", () => {
  // Пост объявлен паспортом (`AirVehicleDefinition.flight.combatStation`), и
  // спрашивают именно его: есть пост — есть бой, нет поста — нет.
  assert.ok(
    !source.includes("COMBAT_HEXACOPTER"),
    "в контур вернулась именная константа боевого коптера",
  );
  assert.ok(
    !source.includes("combatHexacopterRangeRoutes"),
    "в контур вернулся импорт маршрутов конкретной машины на конкретной карте",
  );
  assert.ok(
    source.includes("frame.flight.combatStation"),
    "бой обязан спрашивать паспорт о посте, а не имя задачи",
  );
});

test("ИЗВЕСТНЫЙ ДОЛГ: именными остались кресла и один отладочный признак", () => {
  // Список ЗАМЕРЕН, а не выписан по памяти. Первая редакция теста угадывала —
  // и была неправа в двух строках из шести.
  //
  // Ручное управление — второй куст той же болезни: контур знает, ГДЕ у двух
  // конкретных машин сидит человек. Лечится тем же приёмом, что и пост, —
  // кресло объявляет паспорт, — но это отдельная работа, а не попутная правка.
  //
  // `mamSkyTrain` — признак на `documentElement` для отладочного наблюдения.
  // Он живёт снаружи модели и именем машины ничего не решает, но перечислен
  // здесь наравне с остальными: молчаливое исключение — это способ вырастить
  // долг, не заметив этого.
  const found = [...source.matchAll(MACHINE_WORDS)].map((match) => match[0]);
  assert.deepEqual([...new Set(found)].sort(), [
    "SKY_TRAIN_DRIVER_SEAT",
    "TOWN_HEXACOPTER_PILOT_SEAT",
    "TOWN_HEXACOPTER_PILOT_SEAT_ID",
    "hexacopterPilotMayStand",
    "mamSkyTrain",
  ]);
});
